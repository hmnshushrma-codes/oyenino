// Builds starter-pack-content.js from the Markdown files in content/starter-pack/
// Run from the repo root: node scripts/build-starter-pack-content.mjs
// After a content change, bump `version` here AND STARTER_PACK_VERSION in starter-pack.html,
// then run: node scripts/check-starter-pack.js
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) =>
  readFileSync(new URL(`../content/starter-pack/${f}`, import.meta.url), "utf8").trim() + "\n";

const pack = {
  version: "2026-11-16",
  intro: read("start-here.md"),
  docs: [
    { id: "beginner", title: "Beginner guide", md: read("beginner-guide.md") },
    { id: "tech", title: "Tech guide", md: read("tech-guide.md") },
    { id: "prompts", title: "AI prompt library", md: read("ai-prompt-library.md") },
    { id: "cheatsheet", title: "Cheat sheet", md: read("cheat-sheet.md") },
  ],
};

const out =
  "/* Home Server Starter Pack content. Generated by scripts/build-starter-pack-content.mjs.\n" +
  "   Edit the Markdown files in content/starter-pack/ and run the build script again. Do not edit this file by hand. */\n" +
  "const STARTER_PACK = " +
  JSON.stringify(pack, null, 2) +
  ";\n";

writeFileSync(new URL("../starter-pack-content.js", import.meta.url), out);
console.log("written starter-pack-content.js");
